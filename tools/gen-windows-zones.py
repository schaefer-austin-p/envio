#!/usr/bin/env python3
"""Generate crates/envio-mime/src/invite/zones/windows.rs from CLDR.

Usage: tools/gen-windows-zones.py [path/to/windowsZones.xml]

Without an argument the file is downloaded from the pinned CLDR tag below.
Each Windows zone name maps to its territory-default ("001") IANA zone.
The XML is not committed; only this script and the generated table are.
"""
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

CLDR_TAG = "release-46"
URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr/"
    f"{CLDR_TAG}/common/supplemental/windowsZones.xml"
)
OUT = (
    Path(__file__).resolve().parent.parent
    / "crates/envio-mime/src/invite/zones/windows.rs"
)


def main() -> None:
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            data = r.read()
    rows = {}
    for z in ET.fromstring(data).iter("mapZone"):
        if z.get("territory") == "001":
            rows[z.get("other")] = z.get("type").split()[0]
    lines = [
        f"// Generated by tools/gen-windows-zones.py from CLDR {CLDR_TAG} windowsZones.xml. Do not edit.",
        "",
        "/// Windows zone name to its IANA zone, sorted by name for binary search.",
        "pub(super) const WINDOWS_ZONES: &[(&str, &str)] = &[",
    ]
    for name in sorted(rows):
        lines.append(f'    ("{name}", "{rows[name]}"),')
    lines.append("];")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")


main()
